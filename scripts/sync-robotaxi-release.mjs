#!/usr/bin/env node
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const endpoint = "https://robotaxi.xingbuild.top/deployment-manifest.json";
const controller = new AbortController();
const timeout = setTimeout(() => controller.abort(), 10000);
let response;
try {
  response = await fetch(endpoint, { signal: controller.signal, cache: "no-store" });
} finally {
  clearTimeout(timeout);
}
if (!response?.ok) throw new Error(`Robotaxi release manifest returned ${response?.status || "no response"}`);
const payload = await response.json();
if (!/^v\d+\.\d+\.\d+$/.test(payload.version || "") || !/^[a-f0-9]{40}$/.test(payload.commit || "") || payload.production_url !== "https://robotaxi.xingbuild.top/") {
  throw new Error("Robotaxi release manifest failed the version/commit/target contract");
}
const snapshot = {
  sourceEndpoint: endpoint,
  version: payload.version,
  commit: payload.commit,
  production_url: payload.production_url,
  verifiedAt: new Date().toISOString(),
};
const output = path.join(root, "src/generated/robotaxiReleaseSnapshot.js");
await mkdir(path.dirname(output), { recursive: true });
await writeFile(output, `/** Generated by scripts/sync-robotaxi-release.mjs. */\nexport const robotaxiReleaseSnapshot = Object.freeze(${JSON.stringify(snapshot, null, 2)});\n`);
console.log(JSON.stringify(snapshot));
