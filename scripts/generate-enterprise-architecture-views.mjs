#!/usr/bin/env node
import { createHash } from "node:crypto";
import { execFile } from "node:child_process";
import { mkdir, readFile, rm, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const run = promisify(execFile);
const root = dirname(fileURLToPath(new URL("../package.json", import.meta.url)));
const args = process.argv.slice(2);
const option = (name) => args[args.indexOf(name) + 1];
if (args.some((arg) => arg.startsWith("--") && !["--source", "--output"].includes(arg)) || args.some((arg, index) => arg.startsWith("--") && !args[index + 1])) {
  throw new Error("Usage: node scripts/generate-enterprise-architecture-views.mjs [--source <directory> --output <file>]");
}
const sourceDirectory = option("--source") || join(root, "src/architecture/enterprise-operating-system");
const source = join(sourceDirectory, "model.c4");
const output = option("--output") || join(root, "src/generated/enterpriseArchitectureViews.jsx");
const typeOutput = output.replace(/\.jsx$/, ".d.ts");
const metadataOutput = output.replace(/\.jsx$/, "Meta.js");
const expectedViewIds = ["landscape", "business", "digital", "product"];

async function clearOutputs() {
  await Promise.all([rm(output, { force: true }), rm(typeOutput, { force: true }), rm(metadataOutput, { force: true })]);
}

try {
  await clearOutputs();
  await mkdir(dirname(output), { recursive: true });
  if (!output.endsWith(".jsx")) throw new Error("LikeC4 runtime output must use a .jsx extension");
  await run(join(root, "node_modules/.bin/likec4"), ["validate", sourceDirectory]);
  await run(join(root, "node_modules/.bin/likec4"), ["gen", "react", "--outfile", output, sourceDirectory]);
  await rm(typeOutput, { force: true });
  const generated = await readFile(output, "utf8");
  for (const viewId of expectedViewIds) {
    if (!new RegExp(`id: "${viewId}"`).test(generated)) throw new Error(`LikeC4 generated output is missing view: ${viewId}`);
  }
  const sourceHash = createHash("sha256").update(await readFile(source)).digest("hex");
  await writeFile(metadataOutput, `// Generated by scripts/generate-enterprise-architecture-views.mjs. Do not edit.\nexport const enterpriseArchitectureViewsMeta = ${JSON.stringify({ source: source.endsWith("src/architecture/enterprise-operating-system/model.c4") ? "src/architecture/enterprise-operating-system/model.c4" : source, sourceHash, likec4Version: "1.59.2", viewIds: expectedViewIds }, null, 2)};\n`);
  console.log(`Generated LikeC4 reader runtime for ${expectedViewIds.length} enterprise architecture views`);
} catch (error) {
  await clearOutputs();
  throw error;
}
