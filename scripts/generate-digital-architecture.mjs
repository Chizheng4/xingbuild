#!/usr/bin/env node
import { mkdir, readFile, writeFile } from "node:fs/promises";
import { LikeC4 } from "likec4";

const workspace = new URL("../src/architecture/digital-implementation/", import.meta.url).pathname;
const output = new URL("../src/generated/digitalImplementationArchitecture.js", import.meta.url);
const config = JSON.parse(await readFile(new URL("../src/architecture/digital-implementation/likec4.config.json", import.meta.url), "utf8"));
const likec4 = await LikeC4.fromWorkspace(workspace);
const errors = likec4.getErrors();
if (errors.length) throw new Error(errors.map((error) => error.message ?? String(error)).join("\n"));
const model = await likec4.computedModel();
const data = model.$data;
const nodes = Object.values(data.elements).map((node) => ({
  id: node.id,
  name: node.title,
  kind: node.kind,
  definition: node.description?.txt ?? "",
  role: node.metadata?.role ?? "",
  layer: node.metadata?.layer ?? "",
  layerLabel: node.metadata?.layerLabel ?? "",
}));
const edges = Object.values(data.relations).map((edge) => ({
  id: edge.metadata?.id,
  from: edge.source.model,
  to: edge.target.model,
  label: edge.title,
}));
if (!config.metadata?.architectureId || !config.metadata?.defaultNodeId
  || nodes.length !== 9 || edges.length !== 13
  || nodes.some((node) => !node.definition || !node.role || !node.layer || !node.layerLabel)
  || edges.some((edge) => !edge.id || !edge.label)) {
  throw new Error("LikeC4 digital implementation model is incomplete");
}
const architecture = { id: config.metadata.architectureId, defaultNodeId: config.metadata.defaultNodeId, nodes, edges, tracks: [] };
await mkdir(new URL("../src/generated/", import.meta.url), { recursive: true });
await writeFile(output, `// Generated by scripts/generate-digital-architecture.mjs. Do not edit.\nexport const digitalImplementationArchitecture = ${JSON.stringify(architecture, null, 2)};\n`);
console.log("Generated typed digital implementation architecture data");
